#ifndef PARSE_H
#define PARSE_H

#include "logfile.h"

/* Разбор строки журнала вида «2026-03-15 10:30:00|ERROR|net|текст».
   Первые три вертикальные черты разделяют поля, всё после третьей —
   текст сообщения целиком, даже если в нём встречается черта.

   Возвращает 1 при успехе и 0, если строка не похожа на запись.
   При успехе out->text выделен в куче, и его нужно освободить.
   Подробный разбор с диагностикой появится на практике 6. */
int parse_line(const char *line, LogRecord *out);

#endif /* PARSE_H */
