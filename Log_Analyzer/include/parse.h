#ifndef PARSE_H
#define PARSE_H

#include "logfile.h"

/* Разбор строки журнала вида «2026-03-15 10:30:00|ERROR|net|текст».
   Первые три вертикальные черты разделяют поля, всё после третьей —
   текст сообщения целиком, даже если в нём встречается черта.

   Возвращает LOG_OK, LOG_ERR_FORMAT, если строка не похожа на запись,
   и LOG_ERR_MEMORY, если не хватило памяти на текст. При успехе out->text
   выделен в куче, и его нужно освободить; при ошибке выделенного нет. */
LogStatus parse_line(const char *line, LogRecord *out);

#endif /* PARSE_H */
