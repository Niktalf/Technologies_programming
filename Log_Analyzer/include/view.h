#ifndef VIEW_H
#define VIEW_H

#include "logfile.h"

/* Практика 5: порядок просмотра журнала.

   Сортируются не сами записи, а массив указателей на них. Записи при этом
   не двигаются: обмен двух указателей — это обмен двух адресов,
   а обмен двух записей — копирование трёхсот байт. Поэтому один и тот же
   журнал можно смотреть в разных порядках, не трогая исходные данные. */

typedef enum {
    ORDER_TIME = 0,
    ORDER_LEVEL,
    ORDER_MODULE
} Order;

const char *order_name(Order order);

/* Строит и сортирует массив указателей. Возвращает число записей. */
long view_sort(const LogFile *log, Order order);

/* Печатает первые count записей текущего порядка. */
void view_print(long count);

/* Указатель на запись по номеру в текущем порядке или NULL. */
const LogRecord *view_at(long index);

long view_count(void);

/* Забывает построенный порядок. Вызывается, когда записи журнала поменялись
   местами или загружен другой файл: указатели остались бы на прежние места,
   и порядок стал бы неверным. */
void view_reset(void);

#endif /* VIEW_H */
