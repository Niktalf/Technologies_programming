#pragma once

#include <cstdio>
#include <string>

// Практика 10: класс, владеющий открытым файлом.
//
// Конструктор открывает файл, деструктор закрывает. Других способов
// закрыть файл у класса нет — и не нужно: деструктор объекта на стеке
// вызывается при любом выходе из области видимости, в том числе
// при выходе по исключению. Это и есть RAII: ресурс захватывается
// при создании объекта и освобождается при его разрушении.
//
// Внутри — тот же FILE *, что в версии на C. Стандартный std::ifstream
// устроен так же; здесь класс-владелец написан руками, чтобы было видно,
// как это работает.
//
// Правило пяти: деструктор закрывает файл, копирование запрещено,
// перемещение передаёт файл другому объекту.
class FileReader {
public:
    // Открывает файл на чтение. Если открыть не удалось, возбуждает
    // LogError: объект, который не владеет файлом, не создаётся вовсе,
    // и проверять «а открыт ли он» потом не нужно.
    explicit FileReader(const std::string& path);

    // Закрывает файл. Деструктор не возбуждает исключений: он может
    // вызываться как раз во время обработки другого исключения,
    // и второе исключение в этот момент завершает программу.
    ~FileReader();

    // Копирование запрещено. Копия получила бы тот же FILE *, и два
    // деструктора закрыли бы один файл дважды — неопределённое поведение.
    FileReader(const FileReader&) = delete;
    FileReader& operator=(const FileReader&) = delete;

    // Перемещение разрешено: файл переходит к новому владельцу, у прежнего
    // остаётся nullptr, и его деструктор ничего не закрывает.
    FileReader(FileReader&& other) noexcept;
    FileReader& operator=(FileReader&& other) noexcept;

    // Читает строку целиком, любой длины, без перевода строки и без \r
    // от файлов Windows. Возвращает false, когда строки кончились.
    // Ошибка чтения — LogError.
    bool read_line(std::string& line);

    const std::string& path() const { return path_; }

    // Сколько файлов открыто прямо сейчас всеми объектами FileReader.
    // По этому счётчику видно, что после ста циклов незакрытых файлов нет.
    static int open_count() { return open_count_; }

    // Печатать ли сообщения из конструктора, деструктора и перемещений.
    static bool trace;

private:
    // Закрывает свой файл, если он есть.
    void close() noexcept;

    std::FILE* file_ = nullptr;   // nullptr — объект ничем не владеет (после перемещения)
    std::string path_;

    static int open_count_;
};
