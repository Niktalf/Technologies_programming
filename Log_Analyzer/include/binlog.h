#ifndef BINLOG_H
#define BINLOG_H

#include "logfile.h"
#include "status.h"

/* Практика 8: свой двоичный формат уже разобранного журнала.

   Разбор текста стоит дорого: на каждую строку приходится искать
   разделители и переводить время из строки в число. Двоичный файл
   хранит записи уже разобранными и читается быстрее.

   Формат: сигнатура «LOGB», версия (2 байта), число записей (8 байт),
   затем записи: время (8), уровень (1), длина модуля (1) и его байты,
   длина текста (4) и его байты. Числа раскладываются по байтам вручную,
   младшим байтом вперёд: структуру целиком писать нельзя — в ней указатель
   на текст, который при загрузке бессмыслен, и выравнивающие пропуски.
   Строки пишутся как длина, а потом байты: иначе при чтении нельзя
   понять, где строка кончается. */

#define BINLOG_SIGNATURE "LOGB"
#define BINLOG_VERSION   1

/* Разумные пределы: по ним отвергается испорченный файл до того,
   как по его числам что-нибудь выделится. */
#define BINLOG_TEXT_LIMIT  65536
#define BINLOG_COUNT_LIMIT 50000000L

/* Возвращает LOG_OK, LOG_ERR_ARG, LOG_ERR_OPEN или LOG_ERR_WRITE. */
LogStatus binlog_save(const LogFile *log, const char *path);

/* Возвращает LOG_OK, LOG_ERR_ARG, LOG_ERR_OPEN, LOG_ERR_FORMAT (не та
   сигнатура или версия), LOG_ERR_CORRUPT (файл оборван или в нём
   невозможные значения) или LOG_ERR_MEMORY. При неудаче прежний журнал
   остаётся нетронутым. */
LogStatus binlog_load(LogFile *log, const char *path);

#endif /* BINLOG_H */
