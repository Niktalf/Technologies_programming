#ifndef SORT_H
#define SORT_H

#include "logfile.h"

/* Практика 4: сортировка записей по времени и поиск по отсортированному журналу. */

/* Рекурсивная сортировка слиянием. Устойчива: записи с одинаковым временем
   сохраняют взаимный порядок. Через out_depth сообщает наибольшую глубину
   рекурсии — для миллиона записей она около двадцати, а не миллиона.
   Возвращает LOG_ERR_MEMORY, если не хватило памяти на временный буфер:
   тогда журнал не тронут. */
LogStatus sort_by_time(LogFile *log, int *out_depth);

/* Рекурсивный двоичный поиск первой записи с временем не раньше moment.
   Журнал должен быть отсортирован. Возвращает номер записи;
   если таких записей нет, возвращает log->count. */
long search_not_before(const LogFile *log, Timestamp moment);

/* Сортировка самих записей — нужна только для сравнения с сортировкой
   указателей на практике 5. */
LogStatus sort_records_for_cost(LogRecord *records, long count);

/* Освобождает временный буфер сортировки. */
void sort_free(void);

#endif /* SORT_H */
