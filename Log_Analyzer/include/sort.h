#ifndef SORT_H
#define SORT_H

#include "logfile.h"

/* Практика 4: сортировка записей по времени и поиск по отсортированному журналу. */

/* Рекурсивная сортировка слиянием. Устойчива: записи с одинаковым временем
   сохраняют взаимный порядок. Возвращает наибольшую глубину рекурсии —
   для миллиона записей она около двадцати, а не миллиона. */
int sort_by_time(LogFile *log);

/* Рекурсивный двоичный поиск первой записи с временем не раньше moment.
   Журнал должен быть отсортирован. Возвращает номер записи;
   если таких записей нет, возвращает log->count. */
long search_not_before(const LogFile *log, Timestamp moment);

#endif /* SORT_H */
