#ifndef STATUS_H
#define STATUS_H

/* Практика 8: общее перечисление кодов ошибок.

   Все функции, которые могут не справиться, возвращают код из этого
   перечисления, а не 0 или 1 и не свой собственный набор кодов. Тогда
   вызывающий проверяет результат одинаково везде, а сообщение для
   пользователя получается одной функцией status_text. */

typedef enum {
    LOG_OK = 0,      /* успех */
    LOG_ERR_MEMORY,  /* не хватило памяти */
    LOG_ERR_OPEN,    /* файл не открылся */
    LOG_ERR_FORMAT,  /* неверный формат: не та сигнатура, версия, строка не по формату */
    LOG_ERR_CORRUPT, /* повреждённые данные: оборванный файл, невозможные значения */
    LOG_ERR_ARG,     /* неверный аргумент */
    /* Седьмой код сверх шести из задания: запись на диск может не удаться
       при уже открытом файле (кончилось место), и это не «файл не открыт». */
    LOG_ERR_WRITE    /* ошибка записи */
} LogStatus;

/* Сообщение для пользователя. Для неизвестного кода — "unknown error". */
const char *status_text(LogStatus status);

#endif /* STATUS_H */
