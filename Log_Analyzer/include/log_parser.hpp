#pragma once

#include <string>
#include <vector>

#include "log_book.hpp"
#include "log_record.hpp"

// Практика 11: чтение и разбор текстового журнала.
//
// Строка журнала: «2026-03-15 10:30:00|ERROR|net|текст». Как её разобрать,
// знает этот класс; журнал получает уже готовые записи. На практике 10
// разбор был методом самой записи, а цикл чтения — конструктором журнала,
// и чтобы научить программу второму формату, пришлось бы менять оба класса.
//
// Состояния у класса нет — нет и инварианта. Поэтому методы статические.
class LogParser {
public:
    // Читает текстовый журнал целиком. Файл открывает и закрывает
    // FileReader. Не открылся или не читается — LogError.
    static LogBook read(const std::string& path);

    // Разбирает одну строку. Если строка верная, добавляет запись в конец
    // records и возвращает true. Если нет — records не меняется, false.
    //
    // Запись добавляется в вектор, а не возвращается: вернуть «запись или
    // ничего» одним значением удобно через std::optional, а он появится
    // на практике 16. Пустую запись вернуть нельзя — её не бывает.
    static bool parse_line(const std::string& line, std::vector<LogRecord>& records);

    // Для опыта с исключением: читает файл, как read, но на строке номер
    // fail_at возбуждает исключение. Файл всё равно закрывается.
    static void read_until_failure(const std::string& path, long fail_at);
};
