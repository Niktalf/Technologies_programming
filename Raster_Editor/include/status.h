#ifndef STATUS_H
#define STATUS_H

/* Практика 8: общее перечисление кодов ошибок.

   Каждая функция, которая может не справиться, возвращает один из этих
   кодов, а результат отдаёт через параметр-указатель. Один набор кодов
   на весь проект: модуль файлов, операции над изображением и команды
   говорят на одном языке, и вызывающему не нужно переводить коды
   одного модуля в коды другого. */

typedef enum {
    IMG_OK = 0,   /* успех */
    IMG_ENOMEM,   /* не хватило памяти */
    IMG_EOPEN,    /* файл не открылся */
    IMG_EFORMAT,  /* неверный формат: не PPM или испорчен заголовок */
    IMG_ECORRUPT, /* повреждённые данные: файл оборван или значение вне диапазона */
    IMG_EARG,     /* неверный аргумент */
    /* Седьмой код сверх шести из задания: запись может не удаться у уже
       открытого файла (кончилось место), и это не «файл не открылся». */
    IMG_EWRITE    /* ошибка записи */
} ImgStatus;

/* Текст сообщения для кода. Возвращает строковую константу, освобождать
   её не нужно. */
const char *img_status_text(ImgStatus status);

#endif /* STATUS_H */
