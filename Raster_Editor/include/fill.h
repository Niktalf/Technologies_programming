#ifndef FILL_H
#define FILL_H

#include "image.h"

/* Практика 4: рекурсивная заливка связной области одного цвета.

   Глубина рекурсии может достигать числа пикселей в области: для
   одноцветного изображения 256 x 256 это 65536 вложенных вызовов.
   Стек потока в Windows — один мегабайт, в Linux обычно восемь,
   и такая глубина переполняет его. Поэтому глубина ограничена,
   а при превышении заливка останавливается и честно об этом сообщает.
   Заливка без рекурсии, через собственный стек в куче, появится
   на практике 7. */

#define FILL_MAX_DEPTH 10000

typedef struct {
    int filled;    /* сколько пикселей перекрашено */
    int max_depth; /* наибольшая достигнутая глубина рекурсии */
    int truncated; /* заливка остановлена из-за ограничения глубины */
} FillReport;

FillReport fill_region(Image *image, int x, int y, Pixel color);

#endif /* FILL_H */
