#ifndef FILL_H
#define FILL_H

#include "image.h"

/* Заливка связной области одного цвета.

   Практика 4: рекурсивная заливка упиралась в стек вызовов — глубина
   рекурсии доходит до числа пикселей в области, и одноцветное изображение
   256 x 256 переполняет стек.

   Практика 7: рекурсии больше нет. Точки, которые ещё предстоит
   проверить, лежат в собственном стеке — массиве в куче, который растёт
   через realloc по мере надобности. Куча в сотни раз больше стека
   вызовов, и заливка изображения 8192 x 8192 проходит целиком. */

typedef struct {
    int filled;    /* сколько пикселей перекрашено */
    int max_stack; /* наибольшее число точек, ожидавших проверки */
    int failed;    /* не хватило памяти: заливка остановлена, часть не залита */
} FillReport;

FillReport fill_region(Image *image, int x, int y, Pixel color);

#endif /* FILL_H */
