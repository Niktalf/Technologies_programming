#pragma once

#include <functional>

#include "color.hpp"
#include "image.hpp"

// Практика 13: обход изображения — функция высшего порядка.
//
// Раньше двойной цикл по y и x был написан в каждом фильтре, в каждом
// генераторе узора, в обрезке, повороте, масштабе, в чтении и записи файла —
// двенадцать раз. Все эти циклы одинаковы; различалось только то, что
// делается с одной точкой. Теперь цикл написан один раз, в for_each_point,
// а то, что делается с точкой, передаётся параметром — функцией.

// Операция над пикселем: получает старый цвет, возвращает новый. Сама
// изображение не трогает — пишет в него обход.
using PixelOp = std::function<Color(Color color)>;

// Операция, которой нужны ещё и координаты точки: виньетка, узоры,
// повороты, чтение файла по порядку.
using PositionOp = std::function<Color(Color color, int x, int y)>;

// То, что делается с точкой при обходе только для чтения: запись в файл,
// подсчёты (практика 14).
using PixelVisitor = std::function<void(Color color, int x, int y)>;

// Каждой точке изображения — новый цвет op(старый цвет).
void for_each_pixel(Image& image, const PixelOp& op);

// Каждой точке — новый цвет op(старый цвет, x, y). Точки обходятся строками
// сверху вниз, в строке — слева направо; на этот порядок рассчитывает
// чтение файла.
void for_each_pixel_at(Image& image, const PositionOp& op);

// Обход без изменений: visit(цвет, x, y) для каждой точки в том же порядке.
void visit_pixels(const Image& image, const PixelVisitor& visit);
