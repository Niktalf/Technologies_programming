#ifndef PPM_H
#define PPM_H

#include "image.h"
#include "status.h"

/* Чтение и запись формата PPM.

   Практика 8: поддерживаются обе разновидности — текстовая P3 и двоичная P6.
   Какая перед нами, определяется по сигнатуре. Двоичный файл примерно
   вчетверо меньше и читается быстрее.

   Заголовок устроен так: сигнатура P3 или P6, ширина, высота, максимальное
   значение канала, затем сами данные. Между любыми двумя числами заголовка
   может быть сколько угодно пробелов и переводов строки, а ещё строки
   комментариев, начинающиеся с решётки. */

/* Коды ошибок — общие для всего проекта, из status.h:
   IMG_EOPEN    — файл не открылся;
   IMG_EFORMAT  — не P3 и не P6, заголовок оборван или в нём не число,
                  размеры неразумны;
   IMG_ECORRUPT — данные кончились раньше пикселей или значение канала
                  больше объявленного максимума;
   IMG_ENOMEM   — не хватило памяти под изображение;
   IMG_EWRITE   — не удалось записать файл;
   IMG_EARG     — передан пустой указатель. */

typedef enum {
    PPM_TEXT = 0, /* P3: числа текстом */
    PPM_BINARY    /* P6: байты подряд */
} PpmFormat;

/* Читает файл, сам определяя разновидность по сигнатуре. Память выделяется
   по прочитанным размерам, прежнее изображение освобождается. При ошибке
   изображение не меняется. Через out_format сообщает, что это был за файл;
   можно передать NULL. */
ImgStatus ppm_load(Image *image, const char *path, PpmFormat *out_format);

/* Записывает в выбранной разновидности. */
ImgStatus ppm_save(const Image *image, const char *path, PpmFormat format);

#endif /* PPM_H */
