#ifndef PPM_H
#define PPM_H

#include "image.h"

/* Практика 6: чтение текстового формата PPM.

   Заголовок устроен так: сигнатура P3, ширина, высота, максимальное значение
   канала, затем сами числа. Между любыми двумя числами может быть сколько
   угодно пробелов и переводов строки, а ещё строки комментариев,
   начинающиеся с решётки, — и встречаться они могут в середине заголовка. */

typedef enum {
    PPM_OK = 0,
    PPM_ERR_OPEN,      /* файл не открылся */
    PPM_ERR_SIGNATURE, /* это не P3 */
    PPM_ERR_HEADER,    /* заголовок оборван или в нём не число */
    PPM_ERR_SIZE,      /* размер больше IMAGE_MAX_SIDE */
    PPM_ERR_DATA,      /* файл оборван или значение больше максимума */
    PPM_ERR_MEMORY     /* не хватило памяти под изображение */
} PpmStatus;

const char *ppm_status_text(PpmStatus status);

/* Читает файл в изображение. Память выделяется по прочитанным размерам,
   прежнее изображение освобождается. При ошибке изображение не меняется. */
PpmStatus ppm_load(Image *image, const char *path);

#endif /* PPM_H */
