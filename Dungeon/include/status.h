#ifndef STATUS_H
#define STATUS_H

/* Практика 8: единый набор кодов ошибок для всей игры.

   Функция, которая может не справиться, возвращает код, а результат
   отдаёт через выходной параметр. Вызывающий обязан проверить код:
   по одному виду вызова должно быть понятно, что здесь может случиться
   неудача. */

typedef enum {
    STATUS_OK = 0,
    STATUS_NOT_FOUND,     /* файл не найден или не открылся */
    STATUS_BAD_FORMAT,    /* повреждённый формат: чужой символ, строки разной длины */
    STATUS_NO_MEMORY,     /* не хватило памяти */
    STATUS_BAD_SIZE       /* недопустимый размер: пустой файл, слишком большая карта */
} Status;

/* Сообщение для кода. Строка — константа, освобождать её не нужно. */
const char *status_text(Status status);

#endif /* STATUS_H */
