#ifndef MONSTERS_H
#define MONSTERS_H

/* Практика 7: список монстров, растущий по мере надобности.

   У монстра два свойства — клетка, где он стоит, и здоровье. Пока они
   лежат в двух параллельных массивах: i-й элемент cells и i-й элемент
   hps относятся к одному монстру. Неудобно: каждый массив приходится
   растить отдельно и следить, чтобы они не разошлись. Так оставлено
   намеренно: на практике 8 монстр станет структурой, и массив будет один.

   Ёмкость удваивается, а не растёт на единицу: при росте на единицу
   перенос данных случался бы на каждом добавлении. */

typedef struct {
    int *cells;   /* номер клетки карты, где стоит монстр */
    int *hps;     /* здоровье монстра */
    int count;    /* сколько монстров сейчас */
    int capacity; /* на сколько хватает выделенной памяти */
    int growths;  /* сколько раз ёмкость удваивалась — для наглядности */
} Monsters;

void monsters_init(Monsters *list);

/* Освобождает оба массива и обнуляет указатели. Повторный вызов безопасен. */
void monsters_destroy(Monsters *list);

/* Добавляет монстра. Возвращает 1 при успехе и 0, если памяти не хватило;
   тогда список остаётся прежним и пригодным. */
int monsters_add(Monsters *list, int cell, int hp);

/* Удаляет монстра номер index: на его место переносится последний.
   Порядок монстров не важен, а перенос одного дешевле сдвига всех. */
void monsters_remove(Monsters *list, int index);

/* Номер монстра в клетке cell или -1. */
int monsters_find(const Monsters *list, int cell);

#endif /* MONSTERS_H */
