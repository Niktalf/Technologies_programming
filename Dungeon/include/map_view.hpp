#pragma once

class Hero;
class Map;
class MonsterList;

// Отрисовка: карта, поверх неё монстры и герой.
//
// На практиках 9–10 рисовала сама карта. У класса карты было две причины
// меняться: как хранить клетки и как их показывать. Принцип единственной
// ответственности говорит: одна причина — один класс. Теперь карта хранит,
// а MapView показывает. Захотим рисовать цветом или в окне — поменяется
// только MapView, а карта, генератор и поиск выхода останутся как были.
//
// MapView видит только открытые методы карты, героя и списка монстров:
// размеры, символ клетки, координаты. Дружественности нет — иначе
// разделение было бы только на бумаге: класс отрисовки снова зависел бы
// от того, как карта хранит клетки внутри.
//
// Инварианта нет: у класса нет полей, а значит, и состояния, которое
// можно испортить.
class MapView {
public:
    void show(const Map& map, const Hero& hero, const MonsterList& monsters) const;
};
