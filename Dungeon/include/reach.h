#ifndef REACH_H
#define REACH_H

#include "map.h"

/* Практика 4: достижим ли выход, проверяется рекурсией.
   Практика 5: итоги проверки возвращаются через выходные параметры.
   Практика 7: размер карты задаётся при запуске, поэтому массив пометок
   выделяется в куче под этот размер. Глубина рекурсии не больше числа
   клеток: при пределе 120 на 60 это 7200 вызовов, примерно 430 КБ стека,
   что помещается даже в стек Windows в 1 МБ. */

/* Возвращает 1, если от (x, y) можно дойти до выхода, 0 — если нельзя,
   и -1, если не хватило памяти на пометки. Через *out_cells сообщает,
   сколько клеток обошла проверка, через *out_depth — наибольшую глубину
   рекурсии. Любой из выходных указателей может быть NULL. */
int reach_exit(const Map *map, int x, int y, int *out_cells, int *out_depth);

/* Опыт с переполнением стека: та же рекурсия на открытом поле size x size.
   Возвращает наибольшую глубину рекурсии. */
#define REACH_FIELD_MAX 2000
int reach_open_field(int size);

#endif /* REACH_H */
