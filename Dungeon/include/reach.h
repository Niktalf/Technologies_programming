#ifndef REACH_H
#define REACH_H

#include "map.h"

/* Практика 4: достижим ли выход, проверяется рекурсией.
   Практика 5: итоги проверки возвращаются через выходные параметры,
   а массив пометок стал локальным и передаётся в рекурсию адресом. */

/* Возвращает 1, если от (x, y) можно дойти до выхода. Через *out_cells
   сообщает, сколько клеток обошла проверка, через *out_depth — наибольшую
   глубину рекурсии. Любой из выходных указателей может быть NULL. */
int reach_exit(char map[][MAP_COLS], int x, int y, int *out_cells, int *out_depth);

/* Опыт с переполнением стека: та же рекурсия на открытом поле size x size.
   Возвращает наибольшую глубину рекурсии. */
#define REACH_FIELD_MAX 2000
int reach_open_field(int size);

#endif /* REACH_H */
