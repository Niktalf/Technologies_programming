#ifndef REACH_H
#define REACH_H

#include "map.h"
#include "status.h"

/* Практика 4: достижим ли выход, проверяется рекурсией.
   Практика 5: итоги проверки возвращаются через выходные параметры.
   Практика 7: размер карты задаётся при запуске, поэтому массив пометок
   выделяется в куче под этот размер. Глубина рекурсии не больше числа
   клеток: при пределе 120 на 60 это 7200 вызовов, примерно 430 КБ стека,
   что помещается даже в стек Windows в 1 МБ. */

/* Практика 8: код ошибки — возвращаемым значением, ответ — через
   выходные параметры. STATUS_NO_MEMORY, если не хватило памяти на пометки.
   *out_found — можно ли от (x, y) дойти до выхода; *out_cells — сколько
   клеток обошла проверка; *out_depth — наибольшая глубина рекурсии.
   out_cells и out_depth могут быть NULL. */
Status reach_exit(const Map *map, int x, int y,
                  int *out_found, int *out_cells, int *out_depth);

#endif /* REACH_H */
