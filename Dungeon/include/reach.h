#ifndef REACH_H
#define REACH_H

/* Практика 4: достижим ли выход, проверяется рекурсией.

   Функция помечает клетку посещённой и вызывает себя для четырёх соседей.
   Глубина рекурсии доходит до числа проходимых клеток: на карте 10 на 30
   это пара сотен вызовов, а на большой открытой карте — сотни тысяч,
   и стек вызовов кончается. */

/* Возвращает 1, если от (x, y) можно дойти до выхода. */
int reach_exit(int x, int y);

/* Итоги последней проверки: сколько клеток обошли и наибольшая глубина
   рекурсии. Возвращать несколько значений из одной функции мы научимся
   на практике 5, а пока это отдельные функции. */
int reach_last_cells(void);
int reach_last_depth(void);

/* Опыт с переполнением стека: та же рекурсия на открытом поле size x size
   без единой стены. Возвращает наибольшую глубину рекурсии.
   Размер ограничен REACH_FIELD_MAX. */
#define REACH_FIELD_MAX 2000
int reach_open_field(int size);

#endif /* REACH_H */
