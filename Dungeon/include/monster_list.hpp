#pragma once

#include <vector>

#include "monster.hpp"

// Список монстров уровня.
//
// Инвариант: все монстры в списке живы, и никакие два не стоят в одной
// клетке. Поэтому find всегда находит не больше одного монстра, а мёртвый
// монстр не загораживает дорогу.
//
// На практике 10 список отдавал монстра по ссылке, и игра сама била его,
// сама проверяла, жив ли он, и сама удаляла мёртвого. Забудь игра удалить —
// и в списке остался бы мёртвый монстр. Теперь удар идёт через метод
// списка hit, и удалить мёртвого он не забудет. Ссылку на изменяемого
// монстра список больше не отдаёт никому.
class MonsterList {
public:
    void clear() { monsters_.clear(); }

    // Добавляет монстра с полным здоровьем в клетку (x, y). Возвращает false
    // и ничего не добавляет, если клетка уже занята другим монстром.
    bool add(int x, int y);

    // Номер монстра в клетке (x, y) или -1, если там никого нет.
    int find(int x, int y) const;

    int count() const { return static_cast<int>(monsters_.size()); }

    // Удар по монстру номер index. Возвращает, сколько здоровья у него
    // осталось. Если 0 — монстр погиб и уже убран из списка: на его место
    // встал последний, порядок остальных изменился. Неверный номер или
    // отрицательный урон ничего не меняют, тогда возвращается -1.
    int hit(int index, int damage);

    // Число монстров и первые двадцать из них.
    void print() const;

private:
    std::vector<Monster> monsters_;
};
