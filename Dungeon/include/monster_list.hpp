#pragma once

#include <memory>
#include <vector>

#include "monster.hpp"
#include "monster_query.hpp"

class Game;

// Список монстров уровня.
//
// Инвариант: в списке нет пустых указателей, все монстры живы, и никакие
// два не стоят в одной клетке.
//
// Практика 12: монстры разных видов, поэтому список хранит указатели
// на базовый класс — std::unique_ptr<Monster>. Хранить их по значению,
// std::vector<Monster>, нельзя: Monster абстрактный, и такой вектор
// не соберётся. А будь Monster не абстрактным — при копировании гоблина
// в вектор от него осталась бы только часть Monster: срезка объекта.
// Гоблин перестал бы быть гоблином, и act вызывал бы не его поведение.
//
// unique_ptr владеет монстром: удаляется элемент списка — удаляется
// и монстр, через виртуальный деструктор. Список владеет монстрами — это
// композиция: монстр не живёт дольше своего уровня.
class MonsterList {
public:
    void clear() { monsters_.clear(); }

    // Забирает монстра себе. Возвращает false и уничтожает его, если
    // указатель пуст или клетка уже занята другим монстром.
    bool add(std::unique_ptr<Monster> monster);

    // filter: указатели на монстров, для которых keep отвечает «да», в порядке
    // списка. Указатели, а не копии: через них видны настоящие монстры,
    // и монстр, ударенный после выборки, ударен и в игре. Годны, пока
    // список не изменился.
    std::vector<const Monster*> select(const MonsterPredicate& keep) const;

    // Номер монстра в клетке (x, y) или -1, если там никого нет.
    int find(int x, int y) const;

    int count() const { return static_cast<int>(monsters_.size()); }

    // Монстр по номеру, только для чтения: отрисовке нужен его символ.
    // Изменяемой ссылки список не отдаёт (практика 11).
    const Monster& at(int index) const { return *monsters_[static_cast<std::size_t>(index)]; }

    // Удар по монстру номер index. Возвращает, сколько здоровья у него
    // осталось. Если 0 — монстр погиб и уже убран из списка. Неверный номер
    // или отрицательный урон ничего не меняют, тогда возвращается -1.
    int hit(int index, int damage);

    // Ход всех монстров: каждый делает свой ход через виртуальный вызов
    // act. Список не знает, какие виды в нём лежат, и не проверяет этого.
    // Если герой погиб, остальные уже не ходят.
    void act_all(Game& game);

    // Практика 13: отладка правил хода. Каждый метод получает правило или
    // способ его изменить и применяет ко всем монстрам одинаково.
    void set_rule_all(const MoveRule& rule);
    void make_all_drunk();
    void reset_rules();

    // Число монстров и первые двадцать из них.
    void print() const;

private:
    std::vector<std::unique_ptr<Monster>> monsters_;
};
