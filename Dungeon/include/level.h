#ifndef LEVEL_H
#define LEVEL_H

#include "game.h"
#include "status.h"

/* Практика 8: загрузка уровня из текстового файла.

   Формат — сама карта, строка файла на строку карты:

       ##########
       #@..$...M#
       #..##....#
       #......>.#
       ##########

   # — стена, . — пол, $ — золото, > — выход, @ — герой (ровно один),
   M — монстр. Все строки одной длины. Концы строк могут быть и \n,
   и \r\n: файл, сохранённый в Windows, читается так же.

   Возвращаемые коды:
     STATUS_NOT_FOUND  — файл не открылся;
     STATUS_BAD_SIZE   — файл пуст, строка или число строк больше предела,
                         карта меньше MAP_MIN_SIDE;
     STATUS_BAD_FORMAT — строки разной длины, чужой символ, героя нет
                         или он не один;
     STATUS_NO_MEMORY  — не хватило памяти.

   Результат — через выходной параметр game: в нём заменяются карта
   и монстры, а герой ставится на старт. Состояние игры меняется только
   при успехе: при любой ошибке *game остаётся прежним. Через *out_line
   сообщается номер строки файла, где нашлась ошибка (0 — не про строку). */
Status level_load(const char *path, Game *game, int *out_line);

#endif /* LEVEL_H */
