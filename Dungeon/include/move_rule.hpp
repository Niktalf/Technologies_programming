#pragma once

#include <functional>
#include <string>

class Game;
class Monster;

// Практика 13: правило хода — поведение как значение.
//
// Куда шагнуть, монстр больше не решает кодом своего класса. Он хранит
// правило — функцию — и на своём ходу вызывает её. Правило можно передать
// в конструктор, положить в переменную, заменить во время игры, завернуть
// в другое правило. С функцией обращаются так же, как с числом или
// строкой: это и называется «функции первого класса».

// Шаг: на месте или на одну клетку в одну из четырёх сторон.
enum class Step { stay, north, south, east, west };

int step_dx(Step step);
int step_dy(Step step);

// Тип правила: принимает монстра и состояние игры, возвращает шаг.
// Правило только отвечает на вопрос «куда?» — само ничего не меняет:
// и монстр, и игра переданы по константной ссылке.
//
// Почему std::function, а не указатель на функцию Step (*)(const Monster&,
// const Game&). Указатель — это адрес кода, и только. Лямбде с захватом
// нужно ещё где-то хранить захваченное — например, дальность взгляда
// в chase(8). В адрес функции это не помещается, и такую лямбду указателю
// не присвоить. std::function хранит любую вызываемую вещь с нужной
// сигнатурой: обычную функцию, лямбду без захвата и с захватом.
using MoveRule = std::function<Step(const Monster& self, const Game& game)>;

// Идти к герою, если он ближе sight клеток; иначе стоять.
MoveRule chase(int sight);

// Уходить от героя, если он ближе sight клеток; иначе стоять.
MoveRule flee(int sight);

// Стоять на месте.
MoveRule stand_still();

// Случайный шаг в одну из четырёх сторон.
MoveRule wander();

// «Пьяный» вариант любого правила: с вероятностью 1 к chance — случайный
// шаг, иначе — то, что сказало бы правило base.
//
// Почему это функция высшего порядка. Функция высшего порядка принимает
// функцию или возвращает функцию; drunk делает и то, и другое. Она получает
// правило base — значение типа MoveRule — и возвращает новое правило,
// собранное из старого. Ничего не зная о том, что делает base, drunk
// умеет «напоить» любое правило: chase, flee, wander, даже уже пьяное.
// Без функций как значений для этого понадобился бы отдельный класс
// «пьяного гоблина», «пьяной мыши» и так далее.
MoveRule drunk(MoveRule base, int chance = 6);

// Правило по имени для отладочной команды rule: chase, flee, stand, wander.
// Неизвестное имя — пустое правило: у std::function есть состояние «пусто»,
// и его можно проверить как bool.
MoveRule rule_by_name(const std::string& name);
