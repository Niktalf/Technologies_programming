#pragma once

class Game;

// Практика 12: существо подземелья — общий предок героя и монстров.
//
// Абстрактный класс: у него есть чисто виртуальные методы (= 0), и создать
// объект Creature нельзя — только объект наследника. Это правильно:
// «просто существо» в подземелье не ходит, ходят герой, гоблин, летучая
// мышь. Попытка написать Creature c(1, 1, 5) — ошибка компиляции.
//
// Общие данные — координаты и здоровье — лежат здесь, в одном месте,
// и инвариант здоровья держит тоже базовый класс: наследники меняют его
// только через take_damage и heal.
//
// Инвариант: hp_max() > 0 и 0 <= hp() <= hp_max().
class Creature {
public:
    // Деструктор виртуальный. Игра хранит монстров как указатели на базовый
    // класс и удаляет их через эти указатели. Без virtual delete вызвал бы
    // только ~Creature: деструктор наследника не выполнился бы, и всё, чем
    // владеет наследник, осталось бы неосвобождённым. Стандарт называет это
    // неопределённым поведением. Опыт 8 в demo показывает порядок
    // деструкторов при виртуальном деструкторе.
    //
    // Тело у деструктора есть — он уменьшает счётчик существ, — поэтому
    // он определён в creature.cpp, а не = default.
    virtual ~Creature();

    // Ход существа. Вызывается после каждого хода игрока для каждого
    // существа — через указатель на базовый класс. Какой код выполнится,
    // решает настоящий тип объекта: гоблин идёт к герою, мышь порхает
    // случайно. Это и есть полиморфизм.
    virtual void act(Game& game) = 0;

    // Символ на карте и название для сообщений.
    virtual char symbol() const = 0;
    virtual const char* name() const = 0;

    int x() const { return x_; }
    int y() const { return y_; }
    int hp() const { return hp_; }
    int hp_max() const { return hp_max_; }
    bool alive() const { return hp_ > 0; }

    // Урон с насыщением: ниже нуля здоровье не опускается. Отрицательный
    // урон ничего не делает.
    void take_damage(int amount);

    // Сколько существ сейчас живёт в программе — всех видов вместе.
    static int live_count() { return live_count_; }

protected:
    // Конструктор защищённый: вызвать его могут только наследники из своих
    // конструкторов. hp_max <= 0 — std::invalid_argument.
    Creature(int x, int y, int hp_max);

    // Копирование и перемещение — тоже только для наследников. Открытое
    // копирование базового класса позволило бы срезку: Creature c = goblin;
    // скопировал бы только базовую часть гоблина. У абстрактного класса
    // объекта не создать, но защищённые конструкторы закрывают эту дверь
    // и для ссылок: *first = *second между разными видами не соберётся.
    Creature(const Creature& other);
    Creature& operator=(const Creature&) = default;

    // Лечение с насыщением: выше максимума здоровье не поднимается.
    void heal(int amount);

    // Перестановка в клетку. Проходима ли клетка, проверяет наследник
    // до вызова: он знает, куда ему можно.
    void move_to(int x, int y);

private:
    int x_;
    int y_;
    int hp_max_;
    int hp_;

    static int live_count_;
};
