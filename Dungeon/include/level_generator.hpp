#pragma once

#include "exit_search.hpp"
#include "map.hpp"

// Строитель случайных уровней. Отдельный класс, а не метод карты: карта
// хранит клетки и отвечает на вопросы о них, а как придумать уровень —
// другая задача. Завтра генераторов может стать несколько (пещеры, комнаты
// с коридорами), и карту при этом менять не придётся.
//
// Алгоритм тот же, что map_generate в версии на C (практики 7–8): при
// одинаковых размерах и зерне карта совпадает клетка в клетку.
class LevelGenerator {
public:
    static constexpr int ATTEMPTS = 100;

    // Строит в map случайный уровень width x height, в котором выход
    // достижим из клетки (1, 1). Если перегородки замуровали выход, пробует
    // следующее зерно — до ATTEMPTS раз. Возвращает false, если размер
    // недопустим или проходимый уровень так и не получился.
    bool generate(Map& map, int width, int height, unsigned int seed);

private:
    // Перегородки, золото и выход поверх пустой комнаты.
    void fill(Map& map, unsigned int seed) const;

    // Проверка проходимости: тот же поиск выхода, что у команды check.
    // Объект-поле: генератор пользуется им, а не повторяет обход у себя.
    ExitSearch search_;
};
