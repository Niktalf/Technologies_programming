#pragma once

#include <cstdint>
#include <cstdio>
#include <string>
#include <vector>

#include "record.hpp"

// Практика 10: класс, владеющий файлом журнала.
//
// Конструктор открывает файл, деструктор сбрасывает буфер на диск
// и закрывает. Отдельных методов open и close нет: файл открыт ровно
// столько, сколько живёт объект. Деструктор объекта на стеке вызывается
// при любом выходе из области видимости, в том числе по исключению.
//
// Правило пяти: деструктор закрывает файл, копирование запрещено,
// перемещение передаёт файл другому объекту.
//
// Практика 11: вся работа с журналом — здесь. Хранилище не видит ни байтов,
// ни позиций в файле, ни повреждённого хвоста: оно получает от журнала
// записи (recover) и отдаёт ему записи (append). Как запись выглядит
// в байтах, знает Record, как они лежат в файле — этот класс.
//
// Инвариант: file_ — открытый файл path_ или nullptr у пустого объекта.
// После recover в файле нет повреждённого хвоста: от начала до good_end_
// лежат только целые записи, и запись идёт с good_end_. open_count_ равен
// числу объектов с открытым файлом.
class JournalFile {
public:
    // Пустой объект: файлом не владеет. Так выглядит закрытое хранилище
    // и объект, из которого файл забрали перемещением.
    JournalFile() = default;

    // Открывает журнал на чтение и дозапись; если файла нет, создаёт.
    // При неудаче возбуждает KvError.
    explicit JournalFile(const std::string& path);

    // Сбрасывает буфер и закрывает файл. Исключений не возбуждает.
    ~JournalFile();

    // Копирование запрещено. Копия получила бы тот же FILE *: два
    // деструктора закрыли бы один файл дважды, а записи двух объектов
    // перемешались бы в одном буфере.
    JournalFile(const JournalFile&) = delete;
    JournalFile& operator=(const JournalFile&) = delete;

    // Перемещение: файл переходит к новому владельцу, прежний остаётся пустым.
    JournalFile(JournalFile&& other) noexcept;
    JournalFile& operator=(JournalFile&& other) noexcept;

    bool is_open() const { return file_ != nullptr; }
    const std::string& path() const { return path_; }

    // Перечитывает журнал от начала: все целые записи по порядку добавляет
    // в records. Первая запись, которая не читается целиком или не сходится
    // по контрольной сумме, означает конец пригодных данных: всё дальше
    // отрезается. Возвращает, сколько записей отброшено (0 или 1).
    // Ошибка чтения или обрезки — KvError.
    long recover(std::vector<Record>& records);

    // Практика 14: все целые записи журнала по порядку, для подсчёта мусора.
    // Файл не меняется, а позиция записи после чтения возвращается на место:
    // поэтому метод константный. Читать после recover: тогда в файле только
    // целые записи. Ошибка чтения — KvError.
    std::vector<Record> records() const;

    // Дописывает запись в конец и сразу сбрасывает её на диск.
    // При ошибке — KvError.
    void append(const Record& record);

    // Сколько журналов открыто сейчас всеми объектами — для проверки,
    // что после ста циклов открытых файлов не осталось.
    static int open_count() { return open_count_; }

    // На практике 10 это было открытое статическое поле; теперь флаг закрыт.
    static void set_trace(bool on) { trace_ = on; }

private:
    // Шаги recover и append. Снаружи они не нужны: на практике 10
    // хранилище вызывало их само и должно было помнить порядок.
    void rewind_for_reading();
    Record::ReadResult read_next(Record& out);
    void cut_after_last_record();
    void append_bytes(const std::vector<std::uint8_t>& bytes);

    // Сбрасывает буфер и закрывает свой файл, если он есть.
    void close() noexcept;

    std::FILE* file_ = nullptr;   // nullptr — объект файлом не владеет
    std::string path_;
    long good_end_ = 0;           // конец последней целой записи
    bool reading_ = false;        // последней операцией было чтение

    static int open_count_;
    static bool trace_;
};
