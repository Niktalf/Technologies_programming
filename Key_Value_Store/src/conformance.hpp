#include "engine.hpp"

// Практика 12: общий набор проверок для любого движка.
//
// Проверки пользуются только интерфейсом Engine и ничего не знают о том,
// какой движок им дали. Если движок в памяти проходит набор, а журнальный —
// нет, то либо в журнальном ошибка, либо интерфейс обещает то, чего
// журнальный движок дать не может. Это и есть принцип подстановки в деле:
// любой наследник годится там, где ждут Engine.
//
// Сохранность после перезапуска в набор не входит: интерфейс Engine её
// не обещает, и движок в памяти такую проверку честно провалил бы.
//
// Движок должен быть новым и пустым. Печатает каждую проверку и возвращает,
// сколько из них не прошло.
int run_conformance(Engine& engine);
